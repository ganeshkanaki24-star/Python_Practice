a = 20
b = 10

# assignment operator
print("Assignment Operator:")
print(a+b)
print(a-b)
print(a*b)
print(a/b)

#conditional operator
print("Conditional Operator:")
print(a>b)
print(a<b)
print(a==b)
print(a!=b)
print(a>=b)
print(a<=b)

#logical operator
print("Logical Operator:")
print(a>b and a<b)
print(a>b or a<b)
print(not(a>b and a<b))